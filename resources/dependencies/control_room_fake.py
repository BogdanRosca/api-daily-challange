"""
control_room_fake.py - an in-process stand-in for the Control Room admin API in the QA environment.

DO NOT EDIT THIS FILE. It plays the part of the environment. Anything you dislike in here is how the real
system behaves, and the tests have to live with it. The contract is resources/openapi/control_room_admin.json.

Everywhere
- POST /auth/login returns a bearer token. A token is good for 25 requests; after that every call with it answers
  401 "token expired" (the QA gateway's stand-in for a 15-minute expiry). Log in again for a new one.
- Sites are identified by MPAN core. Every site in resources/data/site_data.json exists on QA, and so do two that
  are not in the pool on purpose: 1300777000119 (Leeds Depot, a fixed, named site) and 1300999000222 (Hull Test Rig,
  reserved for manual QA). Other customers' data lives on QA too: list endpoints without a site filter return it.
- State lives for one pytest run. Every run, including `pytest -k <name>`, starts from the same clean environment.
- Errors (4xx, 5xx) are raised as ApiError with status_code, message, request_id and, for 429, retry_after, the way
  the generated OpenAPI client raises ApiException. Successful calls return a Response with status_code and data.

Sites (site registry)
- GET /sites lists every site (filter with site_type). GET /sites/{mpan_core} reads one: name, site_type, status,
  tags, contact_email and version.
- PATCH /sites/{mpan_core} changes only the fields you send (name, tags, contact_email) and answers 200. It needs
  If-Match: the version you last read (the client's version= argument). Every change gives the site a NEW version.
  A version is opaque: it goes up, but not necessarily by one, so read it back rather than working it out. An
  out-of-date version answers 412 and changes nothing; no version answers 428.
- POST /sites/{mpan_core}/deactivation switches a site off for the rest of the run.
- POST /sites/{mpan_core}/areas adds an area; GET lists them A to Z by name ignoring case, then by id.

Tenders
- POST /sites/{mpan_core}/tenders ({"contract_months": 12 | 24 | 36}) answers 201 with the tender PENDING. A tender
  for an inactive site answers 409. Pricing is asynchronous: after 3 reads of GET /tenders/{tender_id} the tender is
  PRICED with unit_rate_pence_per_kwh (null until then). Pricing for Hull Test Rig is stalled: it stays PENDING.

Hedges
- POST /hedges takes a CSV (header delivery_date,settlement_period,volume_mwh) with one row per settlement period of
  one delivery day, numbered from 1. A day has 48 half-hour periods, except the clock-change days (Europe/London):
  46 on the last Sunday of March, 50 on the last Sunday of October. Anything else is a 422.
  GET /hedges/{hedge_id} summarises it.

Invoices
- POST /sites/{mpan_core}/invoices bills one month and answers 201. amount_pence = consumption_kwh x
  unit_rate_pence_per_kwh, rounded to whole pence, halves away from zero, negative (a credit) for SELL sites.
- The gateway in front of billing is slow: the first POST of a run for each site answers 503, but billing has
  already stored the invoice. Send an Idempotency-Key: a retry with the same key returns the stored invoice (201).
  A retry with a new key, or none, bills the month again.
- GET /sites/{mpan_core}/invoices lists a site's invoices, oldest billing month first.

Forecast uploads
- POST /sites/{mpan_core}/forecast-uploads takes {"file_name", "content"}: a CSV with header "day,period,kwh", one
  line per half-hour period (1-48), kWh a plain decimal with at most 3 decimal places. It answers 202 with an
  upload_id. Only an empty file is refused straight away (422); uploads to Hull Test Rig answer 423 Locked.
- GET /forecast-uploads/{upload_id} goes QUEUED, PROCESSING, then PROCESSED (row_count set, forecast stored) or FAILED
  (errors name the rows; nothing stored). It takes about 0.2 s, longer under load.
- GET /sites/{mpan_core}/forecast returns "forecast_days", oldest first. A new upload replaces the days it contains.

Supply contracts
- POST /sites/{mpan_core}/contracts ({"contract_type": FIXED | FLEX, "start_at", "end_at"}) answers 201. start_at
  and end_at are ISO 8601 instants with a UTC offset; the stored start_date and end_date are their Europe/London dates.
- Two contracts on a site overlap when they share a day. While overlap_policy is REJECT (the default) an overlapping
  contract answers 409. A contract that ends before it starts answers 422.
- GET /sites/{mpan_core}/contracts lists them oldest start_date first, 3 per page, optionally one contract_type. A
  cursor is a position, nothing more: send the same filters with every page.
- GET/PATCH /settings: environment-wide settings, shared by every test in the run. Change one only for as long as
  you need it, and put it back.

Site contacts
- POST /sites/{mpan_core}/contacts adds one (name, email, role PRIMARY | BILLING | OPERATIONS, optional phone): 201.
- PUT /contacts/{contact_id} replaces the whole contact: name, email and role are required and a field you leave
  out is cleared. PATCH /contacts/{contact_id} changes only the fields you send. Both answer 200.
- GET /sites/{mpan_core}/contacts lists them, optionally one role. The order is NOT guaranteed (merged from shards).
- DELETE /contacts/{contact_id} answers 204, or 404 if it's gone. A site always keeps a PRIMARY contact: deleting
  its last one answers 409 and the contact stays.

Consumption
- POST /sites/{mpan_core}/daily-reads stores one total per day ({"day": "2026-11-01", "kwh": "12.500"}): 201. kWh is
  a decimal STRING with up to 3 decimals. A read for a day that already has one replaces it.
- GET /consumption returns daily totals for [from_date, to_date): from_date included, to_date NOT. mpan_core is
  optional: without it you get every site on QA, other customers' included. At most 62 days.
- GET /sites/{mpan_core}/consumption-summary?month=YYYY-MM: total, peak day (the earliest, on a tie), days with reads.

Alerts
- POST /sites/{mpan_core}/alert-rules (name, threshold_kwh as a decimal string, channel EMAIL | SMS): 201.
  GET /alert-rules/{rule_id} reads one; DELETE answers 204, or 404 if it's gone.
- POST /sites/{mpan_core}/evaluations sends one day's consumption: every rule whose threshold the reading is strictly
  ABOVE fires one alert. It answers 201 with the triggered rule ids.
- Evaluations are rate-limited for the whole environment: 6 per second. Over that: 429 with retry_after (seconds).
  A 429 was not processed, so it is safe to send again after waiting.
- GET /sites/{mpan_core}/alerts lists alerts oldest first, 2 per page, with next_cursor (null on the last page).

Meters
- POST /sites/{mpan_core}/meters registers a meter (serial_number, meter_type SMART | AMR, install_date): 201 with
  what you sent plus id, mpan_core, status ACTIVE and registered_at. A serial number is unique across QA (409).
- GET /sites/{mpan_core}/meters lists them in registration order, 5 per page, with next_cursor.
- POST /meters/{meter_id}/readings submits a register reading (running total, kWh string with 3 decimals): 201. It
  must be dated after the latest and can't be lower than it (422). GET lists them oldest first.
"""

