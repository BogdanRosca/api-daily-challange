    def _seed_other_customers(self) -> None:
        """Another customer's reads, already on QA before any test runs."""
        first_day = date(2026, 10, 1)
        for day_offset in range(61):
            read_day = first_day + timedelta(days=day_offset)
            self._daily_reads[self._other_customer_site][read_day.isoformat()] = Decimal(310 + (day_offset * 37) % 90) + Decimal("0.125")

    def _next_id(self, prefix: str) -> str:
        return f"{prefix}_{next(self._ids[prefix])}"

    @staticmethod
    def _copy(site: dict[str, Any]) -> dict[str, Any]:
        return {**site, "tags": list(site["tags"])}

    @staticmethod
    def _is_iso_date(value: Any) -> bool:
        try:
            return isinstance(value, str) and date.fromisoformat(value).isoformat() == value
        except ValueError:
            return False

    def _settlement_periods(self, delivery_date: date) -> int:
        day_start = datetime.combine(delivery_date, datetime.min.time(), tzinfo=self._settlement_zone)
        next_day_start = datetime.combine(delivery_date + timedelta(days=1), datetime.min.time(), tzinfo=self._settlement_zone)
        return int((next_day_start.astimezone(UTC) - day_start.astimezone(UTC)) / timedelta(minutes=30))

    def _advance_upload(self, upload: dict[str, Any]) -> None:
        if upload["status"] in ("PROCESSED", "FAILED"):
            return
        elapsed = time.monotonic() - upload["_accepted_at"]
        if elapsed < self._processing_seconds / 3:
            return
        if elapsed < self._processing_seconds:
            upload["status"] = "PROCESSING"
            return
        periods_by_day, row_errors = self._parse_forecast(upload["_content"])
        if row_errors:
            upload.update({"status": "FAILED", "errors": row_errors})
            return
        for forecast_day, day_periods in periods_by_day.items():
            self._forecasts[upload["mpan_core"]][forecast_day] = {
                "day": forecast_day,
                "period_count": len(day_periods),
                "total_kwh": f"{sum(day_periods.values(), Decimal(0)):.3f}",
            }
        upload.update({"status": "PROCESSED", "row_count": sum(len(day_periods) for day_periods in periods_by_day.values())})

    def _parse_forecast(self, content: str) -> tuple[dict[str, dict[int, Decimal]], list[str]]:
        """The file's kWh by day and period, and every problem found in it."""
        forecast_rows = list(csv.reader(io.StringIO(content)))
        row_errors: list[str] = []
        if not forecast_rows or forecast_rows[0] != self._forecast_header:
            row_errors.append(f"row 1: the header must be {','.join(self._forecast_header)}")
        periods_by_day: dict[str, dict[int, Decimal]] = collections.defaultdict(dict)
        for row_number, forecast_row in enumerate(forecast_rows[1:], start=2):
            if not forecast_row:
                continue
            if len(forecast_row) != 3 or not self._is_iso_date(forecast_row[0]):
                row_errors.append(f"row {row_number}: expected day,period,kwh")
                continue
            if not forecast_row[1].isdigit() or not 1 <= int(forecast_row[1]) <= self._forecast_periods_per_day:
                row_errors.append(f"row {row_number}: period must be 1 to {self._forecast_periods_per_day}")
                continue
            if not re.fullmatch(r"\d+(\.\d{1,3})?", forecast_row[2]):
                row_errors.append(f"row {row_number}: kwh must be a plain decimal with at most 3 decimal places")
                continue
            periods_by_day[forecast_row[0]][int(forecast_row[1])] = Decimal(forecast_row[2])
        for forecast_day, day_periods in periods_by_day.items():
            if len(day_periods) != self._forecast_periods_per_day:
                row_errors.append(f"{forecast_day}: {len(day_periods)} periods, expected {self._forecast_periods_per_day}")
        return periods_by_day, row_errors

    def _check_contact(self, path: str, payload: dict[str, Any], request_id: str, *, whole: bool) -> None:
        allowed_fields = {"name", "email", "role", "phone"}
        if set(payload) - allowed_fields or (not whole and not payload):
            raise self._reject(path, f"send only {', '.join(sorted(allowed_fields))}", request_id)
        if whole and not all(payload.get(field_name) for field_name in ("name", "email", "role")):
            raise self._reject(path, "name, email and role are required", request_id)
        if "email" in payload and "@" not in str(payload["email"]):
            raise self._reject(path, "email must be an email address", request_id)
        if "role" in payload and payload["role"] not in self._contact_roles:
            raise self._reject(path, f"role must be one of {', '.join(self._contact_roles)}", request_id)

    def _page(self, path: str, resource: str, resources: list[dict[str, Any]], cursor: str | None, request_id: str) -> Response:
        page_size = self._page_sizes[resource]
        offset = 0
        if cursor is not None:
            if not re.fullmatch(r"cur_\d+", cursor) or int(cursor[4:]) > len(resources):
                log.info(f"{path}?cursor={cursor} -> 400")
                raise _HttpError(HTTPStatus.BAD_REQUEST, f"unknown cursor {cursor}", request_id)
            offset = int(cursor[4:])
        page_items = resources[offset : offset + page_size]
        next_offset = offset + page_size
        next_cursor = f"cur_{next_offset}" if next_offset < len(resources) else None
        log.info(f"{path}" + (f"?cursor={cursor}" if cursor else "") + f" -> 200 ({len(page_items)} {resource}, next_cursor {next_cursor})")
        return Response(HTTPStatus.OK, {"items": [dict(page_item) for page_item in page_items], "next_cursor": next_cursor})

    def _reject(self, path: str, message: str, request_id: str) -> _HttpError:
        log.info(f"{path} -> 422 ({message})")
        return _HttpError(HTTPStatus.UNPROCESSABLE_ENTITY, message, request_id)

    def _find_site(self, path: str, mpan_core: str, request_id: str) -> dict[str, Any]:
        if mpan_core not in self._sites:
            log.info(f"{path} -> 404")
            raise _HttpError(HTTPStatus.NOT_FOUND, f"site {mpan_core} not found", request_id)
        return self._sites[mpan_core]

    @staticmethod
    def _find(path: str, store: dict[str, Any], resource_id: str, resource_name: str, request_id: str) -> Any:
        if resource_id not in store:
            log.info(f"{path} -> 404")
            raise _HttpError(HTTPStatus.NOT_FOUND, f"{resource_name} {resource_id} not found", request_id)
        return store[resource_id]

    def _authorise(self, path: str, token: str) -> str:
        request_id = str(uuid.uuid4())
        if token not in self._requests_left:
            raise _HttpError(HTTPStatus.UNAUTHORIZED, "invalid token", request_id)
        if self._requests_left[token] <= 0:
            log.info(f"{path} -> 401 ({token} expired)")
            raise _HttpError(HTTPStatus.UNAUTHORIZED, f"token expired after {self._token_request_limit} requests; log in again", request_id)
        self._requests_left[token] -= 1
        return request_id


