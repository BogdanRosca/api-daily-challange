class ApiError(Exception):
    """Non-2xx response from the API."""

    def __init__(self, status_code: int, message: str, request_id: str, retry_after: float | None = None) -> None:
        super().__init__(f"{status_code} {message} (request_id {request_id})")
        self.status_code = status_code
        self.message = message
        self.request_id = request_id
        self.retry_after = retry_after


@dataclass
class Response:
    status_code: int
    data: Any = None


class _HttpError(Exception):
    """An error response on the wire. ControlRoomClient turns it into ApiError."""

    def __init__(self, status_code: int, message: str, request_id: str, retry_after: float | None = None) -> None:
        super().__init__(message)
        self.status_code = status_code
        self.message = message
        self.request_id = request_id
        self.retry_after = retry_after


